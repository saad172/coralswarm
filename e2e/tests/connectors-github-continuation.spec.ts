import { expect, test } from '../lib/fixtures';
import { personalUser } from '../lib/isolation';
import { selectRows } from '../lib/stack-db';
import { PORTS } from '../stack/config.mjs';
import { freshPayload } from '../lib/readModels';

test('GitHub bounded import resumes persisted page two and floor after pause', async ({ request }, testInfo) => {
  test.setTimeout(120000);
  const { api } = await personalUser(request, 'gh-page');
  await api.graphs();
  const installationId = Math.floor(Date.now() / 1000) + 30000;
  const user = `pages-${installationId}`;
  const fake = `http://127.0.0.1:${PORTS.fakes}`;
  expect((await request.post(`${fake}/__github/accounts`, { data: { user, installationId } })).status()).toBe(201);
  const start = await api.json('POST', '/v1/connectors/github/connect', { return_to: 'wizard' });
  const consent = new URL(`${fake}/github/apps/e2e-github/installations/new`);
  consent.searchParams.set('state', new URL(start.authorize_url).searchParams.get('state')!);
  consent.searchParams.set('user', user);
  const grant = await request.get(consent.href, { maxRedirects: 0 });
  expect((await request.get(grant.headers().location, { maxRedirects: 0 })).headers().location).toContain(`installation_id=${installationId}`);
  await api.json('PATCH', '/v1/connectors/github/sources/repos', { enabled: true });
  await api.json('PUT', '/v1/connectors/github/sources/repos/scope', { mode: 'pick', item_ids: [String(installationId * 10 + 1)] });
  const jobs = () => selectRows(`SELECT j.status::text FROM jobs j JOIN github_watched_repos r ON r.id::text=j.payload->>'repo_row_id' WHERE j.kind='GithubBackfill' AND r.installation_id=${installationId}`);
  const settled = () => expect.poll(() => jobs().filter(r => ['pending', 'running'].includes(r[0])).length, { timeout: 30000 }).toBe(0);
  await settled();
  const cursor = () => JSON.parse(selectRows(`SELECT narrative_cursor::text FROM github_watched_repos WHERE installation_id=${installationId} AND repo_id=${installationId * 10 + 1}`)[0][0]);
  expect(cursor().issue.done).toBe(true);
  // Switch only external provider data after the automatic import has settled.
  await request.post(`${fake}/__github/config`, { data: { user, continuation: true, holdPageTwo: true } });
  await request.delete(`${fake}/__github/requests?user=${user}`);
  await api.json('POST', '/v1/connectors/github/sources/repos/backfill', { days: 30 });
  await expect.poll(() => cursor().issue.page_url).toContain('page=2');
  await api.json('PATCH', '/v1/connectors/github/sources/repos', { paused: true });
  await settled(); // A rate-limit continuation tick must actually consume the paused job.
  const paused = cursor();
  expect(paused.issue.seen).toBe(1);
  expect(paused.issue.done).toBe(false);
  expect(paused.issue.page_url).toContain('page=2');
  expect(Date.parse(paused.window_floor)).toBeGreaterThan(Date.now() - 31 * 86400000);
  expect(Date.parse(paused.window_floor)).toBeLessThan(Date.now() - 29 * 86400000);
  const before = await (await request.get(`${fake}/__github/requests?user=${user}`)).json();
  expect(before.some((r: any) => r.path.endsWith('/issues/101/comments'))).toBe(true);
  expect(before.some((r: any) => r.path.endsWith('/issues/102/comments'))).toBe(false);
  await request.post(`${fake}/__github/config`, { data: { user, holdPageTwo: false } });
  expect(cursor()).toEqual(paused);
  await request.delete(`${fake}/__github/requests?user=${user}`);
  await api.json('PATCH', '/v1/connectors/github/sources/repos', { paused: false });
  await expect.poll(() => cursor().issue.done, { timeout: 30000 }).toBe(true);
  await settled();
  const finished = cursor();
  expect(finished.window_floor).toBe(paused.window_floor);
  expect(finished.issue.seen).toBe(2);
  expect(finished.issue.page_url).toBeNull();
  for (const type of ['pr', 'issue', 'release', 'commit']) expect(finished[type].done).toBe(true);
  expect(jobs().every(r => r[0] === 'done')).toBe(true);
  const after = await (await request.get(`${fake}/__github/requests?user=${user}`)).json();
  const listings = after.filter((r: any) => r.path.endsWith('/issues'));
  expect(listings).toHaveLength(1);
  expect(listings[0].query.page).toBe('2');
  expect(after.some((r: any) => r.path.endsWith('/issues/101/comments'))).toBe(false);
  expect(after.some((r: any) => r.path.endsWith('/issues/102/comments'))).toBe(true);
  expect(after.some((r: any) => r.path.endsWith('/issues/103/comments'))).toBe(false);
  await freshPayload(api, '/v1/connectors/github', (c: any) => c.status === 'active');
  const captures = await api.json('GET', '/v1/connectors/github/captures');
  const continuedAtom = captures.items.find((item: any) => item.title?.includes('GitHub continuation issue 102'));
  expect(continuedAtom).toBeTruthy();
  expect(captures.items.some((item: any) => item.title?.includes('GitHub continuation issue 103'))).toBe(false);
  await expect.poll(async () => (await api.call('GET', `/v1/atoms/${continuedAtom.atom_id}`)).status()).toBe(200);
  expect((await api.json('GET', `/v1/atoms/${continuedAtom.atom_id}`)).content).toContain('aged 10 days');
  await testInfo.attach('persisted-github-continuation', { body: JSON.stringify({ paused, finished, before, after }, null, 2), contentType: 'application/json' });
});
